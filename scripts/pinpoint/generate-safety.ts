import { writeFileSync } from 'node:fs';
import { pinpointPuzzles } from '../../worker/src/games/pinpoint/puzzles.ts';
import { normalizePinpoint, distance, typoLimit } from '../../worker/src/games/pinpoint/match.ts';

const puzzles = pinpointPuzzles();
const normalized = puzzles.map((p) => p.accepted.map(normalizePinpoint));
const masks = normalized.map((answers, i) =>
  answers.reduce((mask, answer, index) => {
    const safe = normalized.every(
      (others, j) =>
        i === j ||
        others.every((other) => distance(answer, other) > typoLimit(answer) + typoLimit(other)),
    );
    return safe ? mask | (1 << index) : mask;
  }, 0),
);
writeFileSync(
  new URL('../../worker/src/games/pinpoint/safety.ts', import.meta.url),
  `// Generated by scripts/pinpoint/generate-safety.ts.\nexport const TYPO_MASKS: number[] = ${JSON.stringify(masks)};\n`,
);
