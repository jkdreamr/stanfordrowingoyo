import { createCipheriv, createHash, createHmac } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, URL } from 'node:url';
import { Buffer } from 'node:buffer';
import process from 'node:process';
import console from 'node:console';
import { format } from 'prettier';
import { crosswordSlots } from '../../shared/games/crossword.ts';

export const root = new URL('../../', import.meta.url);
export async function sourcePath(path) {
  if (path) return path;
  const real = new URL('scripts/crossword/puzzles.json', root);
  try {
    await readFile(real);
    return real;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  return new URL('scripts/crossword/fixtures/sample.json', root);
}
export async function compile(path) {
  const source = JSON.parse(await readFile(await sourcePath(path), 'utf8'));
  if (
    !/^\d{4}-\d{2}-\d{2}$/.test(source.start) ||
    new Date(source.start).toISOString().slice(0, 10) !== source.start ||
    !source.puzzles.length
  )
    throw new Error('Invalid schedule');
  const records = source.puzzles.map(({ grid, across, down }, day) => {
    if (grid.length !== 5 || grid.some((row) => !/^[A-Z#]{5}$/.test(row)))
      throw new Error(`Invalid grid ${day}`);
    const flat = grid.join('');
    const blocks = [...flat].flatMap((c, i) => (c === '#' ? [i] : []));
    if (blocks.some((i) => flat[24 - i] !== '#')) throw new Error(`Asymmetric grid ${day}`);
    const slots = crosswordSlots(blocks).sort(
      (a, b) => a.dir.localeCompare(b.dir) || a.number - b.number,
    );
    if (
      ![...flat].every(
        (c, i) =>
          c === '#' ||
          ['across', 'down'].every((dir) =>
            slots.some((s) => s.dir === dir && s.cells.includes(i)),
          ),
      )
    )
      throw new Error(`Unchecked or short entry ${day}`);
    for (const dir of ['across', 'down']) {
      const clues = dir === 'across' ? across : down;
      if (!clues || Object.keys(clues).length !== slots.filter((s) => s.dir === dir).length)
        throw new Error(`Clue count ${day}`);
    }
    return [
      flat,
      ...slots.map((slot) => {
        const text = (slot.dir === 'across' ? across : down)[slot.number];
        if (typeof text !== 'string' || !text.trim())
          throw new Error(`Missing clue ${day}/${slot.number}`);
        return text;
      }),
    ];
  });
  const plaintext = Buffer.from(JSON.stringify(['oyo-crossword-v1', ...records]));
  const sha256 = createHash('sha256').update(plaintext).digest('hex');
  const seed = '9a6bf0200128ccfa3e7dbd8a57c8c513144864bfcd720b03df01cf2a5d919820';
  const derive = (label) =>
    createHmac('sha256', Buffer.from(seed, 'hex')).update(`${label}:${sha256}`).digest();
  const key = derive('key'),
    iv = derive('iv').subarray(0, 12);
  const cipher = createCipheriv('aes-256-gcm', key, iv);
  const dat = Buffer.concat([cipher.update(plaintext), cipher.final(), cipher.getAuthTag()]);
  const metadata = {
    key: key.toString('base64'),
    iv: iv.toString('base64'),
    sha256,
    count: records.length,
    start: source.start,
  };
  const ts = `// Generated by scripts/crossword/build.mjs.\nexport const CROSSWORD_DATA = ${JSON.stringify(
    metadata,
    null,
    2,
  )
    .replace(/"([^"]+)":/g, '$1:')
    .replace(/"/g, "'")} as const;\n`;
  return { dat, ts: await format(ts, { parser: 'typescript', singleQuote: true, printWidth: 96 }) };
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { dat, ts } = await compile(process.argv[2]);
  await mkdir(new URL('web/public/games/', root), { recursive: true });
  await writeFile(new URL('web/public/games/crossword.dat', root), dat);
  await writeFile(new URL('worker/src/games/crossword/data.ts', root), ts);
  console.log(`Built crossword ciphertext: ${dat.length} bytes`);
}
